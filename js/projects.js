const grid =
  document.querySelector("#projects-grid") ||
  document.querySelector("#projectsGrid") ||
  document.querySelector(".projects-grid") ||
  document.querySelector(".project-grid") ||
  document.querySelector("#project-grid") ||
  document.querySelector("#projects-container");

const filters = document.querySelectorAll(
  "[data-filter], .filter-button, .filter-btn, .project-filter"
);

function imageURL(filename) {
  return (
    IMAGE_PATH +
    filename
      .split("/")
      .map(part => encodeURIComponent(part))
      .join("/")
  );
}

function escapeHTML(value) {
  return String(value).replace(/[&<>"']/g, character => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    '"': "&quot;",
    "'": "&#39;"
  })[character]);
}

function folderCard(project, index) {
  const cover = imageURL(project.cover);

  const backImages = project.images
    .filter(image => image !== project.cover)
    .slice(0, 2);

  const backLayers = backImages.map((image, layerIndex) => `
    <img
      class="folder-back folder-back-${layerIndex + 1}"
      src="${imageURL(image)}"
      alt=""
      loading="lazy"
      onerror="this.style.display='none'"
    >
  `).join("");

  return `
    <article
      class="project-card folder-card"
      data-category="${escapeHTML(project.category)}"
      style="--card-index:${index}"
    >
      <a
        class="folder-link"
        href="project.html?id=${encodeURIComponent(project.id)}"
        aria-label="Open ${escapeHTML(project.title)} project"
      >
        <div class="folder-artwork">
          <div class="folder-tab"></div>

          ${backLayers}

          <div class="folder-front">
            <img
              src="${cover}"
              alt="${escapeHTML(project.title)} cover"
              loading="${index < 2 ? "eager" : "lazy"}"
              onerror="this.classList.add('image-not-found')"
            >
          </div>

          <span class="folder-open-label">VIEW PROJECT ↗</span>

          <span class="folder-count">
            ${String(project.images.length).padStart(2, "0")} DESIGNS
          </span>
        </div>

        <div class="folder-information">
          <span class="folder-category">
            ${escapeHTML(project.category.replace("-", " "))}
          </span>

          <h2>${escapeHTML(project.title)}</h2>

          <p class="project-preview">
            ${escapeHTML(project.preview)}
          </p>
        </div>
      </a>
    </article>
  `;
}

function renderProjects(category = "all") {
  if (!grid) {
    console.error(
      "Projects grid not found. Check the gallery container in projects.html."
    );
    return;
  }

  const visibleProjects = projects.filter(project =>
    category === "all" || project.category === category
  );

  grid.innerHTML = visibleProjects.length
    ? visibleProjects.map(folderCard).join("")
    : `<p class="projects-empty">No projects in this category yet.</p>`;

  grid.classList.add("folder-grid");
}

if (grid) {
  renderProjects();

  filters.forEach(button => {
    button.addEventListener("click", () => {
      const category =
        button.dataset.filter ||
        button.dataset.category ||
        "all";

      filters.forEach(item => item.classList.remove("active"));
      button.classList.add("active");

      renderProjects(category);
    });
  });
}

const detailContainer =
  document.querySelector("#project-detail") ||
  document.querySelector(".project-detail");

if (detailContainer) {
  const params = new URLSearchParams(window.location.search);

  const selectedProject = projects.find(
    project => project.id === params.get("id")
  );

  if (!selectedProject) {
    detailContainer.innerHTML = `
      <div class="project-not-found">
        <h1>Project not found</h1>
        <a href="projects.html">← Back to projects</a>
      </div>
    `;
  } else {
    document.title = `${selectedProject.title} — Israr Ahmed Mir`;

    detailContainer.innerHTML = `
      <header class="detail-heading">
        <a href="projects.html" class="detail-back">
          ← ALL PROJECTS
        </a>

        <p class="detail-category">
          ${escapeHTML(selectedProject.category.replace("-", " "))}
        </p>

        <h1>${escapeHTML(selectedProject.title)}</h1>

        <p>${escapeHTML(selectedProject.description)}</p>

        <span>
          ${String(selectedProject.images.length).padStart(2, "0")} DESIGNS
        </span>
      </header>

      <div class="detail-gallery">
        ${selectedProject.images.map((image, index) => `
          <figure class="detail-image">
            <img
              src="${imageURL(image)}"
              alt="${escapeHTML(selectedProject.title)} — design ${index + 1}"
              loading="${index < 2 ? "eager" : "lazy"}"
              onerror="this.closest('figure').classList.add('broken-image')"
            >

            <figcaption>
              DESIGN ${String(index + 1).padStart(2, "0")}
            </figcaption>
          </figure>
        `).join("")}
      </div>
    `;
  }
}
